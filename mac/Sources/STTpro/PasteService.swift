import AppKit
import Carbon.HIToolbox
import STTproCore

/// Puts text on the clipboard, sends ⌘V to the frontmost app, then restores
/// whatever was on the clipboard before (unless the user copied something
/// new in the meantime).
@MainActor
enum PasteService {
    enum PasteError: LocalizedError {
        case accessibilityRequired
        var errorDescription: String? {
            "STTpro needs Accessibility permission to paste. The text is on your clipboard — press ⌘V."
        }
    }

    /// Clipboard managers (Maccy, Raycast, Paste, …) skip items with this type.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Time the target app gets to read the clipboard before it is restored.
    private static let pasteSettle: Duration = .milliseconds(450)

    static func copy(_ text: String, transient: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            item.setData(Data(), forType: transientType)
            item.setData(Data(), forType: autoGeneratedType)
        }
        pb.writeObjects([item])
    }

    static func paste(_ text: String, into target: NSRunningApplication?, restoreClipboard: Bool) async throws {
        let pb = NSPasteboard.general
        let snapshot = restoreClipboard ? snapshotPasteboard(pb) : nil

        copy(text, transient: restoreClipboard)
        let ourChangeCount = pb.changeCount

        guard AXIsProcessTrusted() else {
            // Leave the transcript on the clipboard so the user can paste manually.
            copy(text)
            throw PasteError.accessibilityRequired
        }

        if let target, !target.isTerminated, NSWorkspace.shared.frontmostApplication?.processIdentifier != target.processIdentifier {
            target.activate()
            for _ in 0..<20 where NSWorkspace.shared.frontmostApplication?.processIdentifier != target.processIdentifier {
                try? await Task.sleep(for: .milliseconds(25))
            }
        }
        try? await Task.sleep(for: .milliseconds(30))

        sendCommandV()

        guard let snapshot else { return }
        try? await Task.sleep(for: pasteSettle)
        if pb.changeCount == ourChangeCount {
            restore(snapshot, to: pb)
            Log.info("Clipboard restored")
        } else {
            Log.info("Clipboard changed during paste; not restoring")
        }
    }

    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        // Ignore physically held modifiers (e.g. ⌃ still down from ⌃Space).
        let vKey = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private static func snapshotPasteboard(_ pb: NSPasteboard) -> Snapshot {
        (pb.pasteboardItems ?? []).map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            return dict
        }
    }

    private static func restore(_ snapshot: Snapshot, to pb: NSPasteboard) {
        pb.clearContents()
        guard !snapshot.isEmpty else { return }
        let items: [NSPasteboardItem] = snapshot.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        pb.writeObjects(items)
    }
}
